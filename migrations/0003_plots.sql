CREATE TABLE plots (
  id INTEGER PRIMARY KEY,
  owner TEXT REFERENCES users(id) ON DELETE SET NULL,
  owner_name TEXT,
  bought_at INTEGER
);
CREATE UNIQUE INDEX plots_owner ON plots(owner) WHERE owner IS NOT NULL;
WITH RECURSIVE n(i) AS (SELECT 0 UNION ALL SELECT i + 1 FROM n WHERE i < 23) INSERT INTO plots (id) SELECT i FROM n;
