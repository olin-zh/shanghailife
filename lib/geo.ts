// 真实经纬度 → 游戏地图坐标。
// 市中心按真实比例（1 格约 75 米，以人民广场附近为原点，北为 -z、东为 +x）；
// 离中心超过约 5 公里的地方，方向不变、距离往里收（只算 30%），让虹桥、张江、松江不至于远到走不过去。
const LON0 = 121.475, LAT0 = 31.228;
const KX = 1271, KZ = 1480; // 每度经/纬度对应的格数（北纬 31° 附近）
const R0 = 70, SQUEEZE = 0.3;

export function geo(lon: number, lat: number) {
  const x = (lon - LON0) * KX, z = -(lat - LAT0) * KZ;
  const r = Math.hypot(x, z);
  if (r <= R0) return { x, z };
  const f = (R0 + (r - R0) * SQUEEZE) / r;
  return { x: x * f, z: z * f };
}

// 网格：每格 4 个单位（市区约 300 米），网格从 (XMIN, ZMIN) 开始
export const CELL = 4, XMIN = -152, ZMIN = -132;
export const onGrid = (p: { x: number; z: number }) => ({ x: XMIN + (Math.floor((p.x - XMIN) / CELL) + 0.5) * CELL, z: ZMIN + (Math.floor((p.z - ZMIN) / CELL) + 0.5) * CELL });

